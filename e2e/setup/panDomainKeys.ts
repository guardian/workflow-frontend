export type PanDomainKeys = {
    privateKeyPem: string;
    privateKeyBase64: string;
    publicKeyBase64: string;
};

export function pemToBase64(key: string): string {
    return key
        .replace(/-----BEGIN [^-]+-----/g, "")
        .replace(/-----END [^-]+-----/g, "")
        .replace(/\s+/g, "");
}

